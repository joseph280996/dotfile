#!/usr/bin/env python3
"""Save the current kitty OS window (all tabs + window cwds) as a session file.

Usage: save-session.py [output-session-file]

Requires allow_remote_control to be enabled in kitty.conf. Run it from a
keybinding inside kitty so KITTY_LISTEN_ON is available, e.g.:

    map ctrl+shift+f7 launch --type=overlay --hold save-session.py

Load the saved session with:
    kitty --session sessions/default.session
"""
import json
import os
import shlex
import subprocess
import sys

DEFAULT_OUTPUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "sessions", "default.session")

def main() -> int:
    output = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_OUTPUT

    cmd = ["kitty", "@", "ls", "--self"]
    listen_on = os.environ.get("KITTY_LISTEN_ON")
    if listen_on:
        cmd = ["kitty", "@", "--listen-on", listen_on, "ls", "--self"]

    try:
        raw = subprocess.check_output(cmd, text=True, stderr=subprocess.PIPE)
    except FileNotFoundError:
        print("error: kitty binary not found in PATH", file=sys.stderr)
        return 1
    except subprocess.CalledProcessError as e:
        print(f"error: could not query kitty (is allow_remote_control enabled?): {e.stderr.strip()}", file=sys.stderr)
        return 1

    try:
        os_windows = json.loads(raw)
    except json.JSONDecodeError as e:
        print(f"error: unexpected kitty @ ls output: {e}", file=sys.stderr)
        return 1

    tabs = os_windows[0]["tabs"] if os_windows else []

    lines = ["# Generated by save-session.py -- do not edit while kitty may overwrite it"]
    for tab in tabs:
        windows = tab.get("windows", [])
        if not windows:
            continue
        tab_title = tab.get("title", "")
        for i, win in enumerate(windows):
            cwd = win.get("cwd") or os.path.expanduser("~")
            if i == 0:
                opts = f"--cwd {shlex.quote(cwd)}"
                if tab_title:
                    opts += f" --title {shlex.quote(tab_title)}"
                lines.append(f"new_tab {opts}")
            else:
                lines.append(f"new_window --cwd {shlex.quote(cwd)}")

    if len(lines) <= 1:
        print("error: no tabs/windows found to save", file=sys.stderr)
        return 1

    os.makedirs(os.path.dirname(output), exist_ok=True)
    with open(output, "w") as f:
        f.write("\n".join(lines) + "\n")

    print(f"Session saved: {output} ({len(tabs)} tab(s))")
    return 0

if __name__ == "__main__":
    sys.exit(main())
